// Helper to generate dynamic dates relative to current time
function timeAgo(days, hours = 10, minutes = 0) {
  const d = new Date()
  d.setDate(d.getDate() - days)
  d.setHours(hours, minutes, 0, 0)
  return d.toISOString()
}

